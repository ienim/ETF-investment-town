function seededRandom(seed: number) {
  const x = Math.sin(seed * 97.13 + 11.7) * 10000;
  return x - Math.floor(x);
}

function weightedPick<T>(items: T[], getWeight: (item: T, index: number) => number, seed: number) {
  const total = items.reduce((sum, item, index) => sum + Math.max(0.01, getWeight(item, index)), 0);
  let cursor = seededRandom(seed) * total;

  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    cursor -= Math.max(0.01, getWeight(item, index));
    if (cursor <= 0) return item;
  }

  return items[0];
}

function getTypeWeight(day: number, eventType: NonNullable<MarketEvent["eventType"]>) {
  if (day <= 3) {
    return eventType === "daily" ? 1.25 : eventType === "important" ? 0.7 : 0.18;
  }

  if (day >= 10) {
    return eventType === "important" ? 1.1 : eventType === "blackSwan" ? 0.34 : 0.85;
  }

  return eventType === "daily" ? 1 : eventType === "important" ? 0.82 : 0.24;
}

function getAnchorEventType(day: number): NonNullable<MarketEvent["eventType"]> {
  const roll = seededRandom(day * 13);
  const blackSwanThreshold = day >= 9 ? 0.12 : day <= 3 ? 0.03 : 0.06;
  const importantThreshold = day >= 8 ? 0.44 : 0.28;

  if (roll < blackSwanThreshold) return "blackSwan";
  if (roll < importantThreshold) return "important";
  return "daily";
}

function getEventWeight(day: number, event: MarketEvent) {
  const type = event.eventType ?? "daily";
  const targetCountBoost = 1 + event.targetEtfs.length * 0.03;
  const truthBias = event.truthiness === "true" ? 1 : event.truthiness === "noise" ? 0.7 : 0.78;
  return getTypeWeight(day, type) * targetCountBoost * truthBias;
}

